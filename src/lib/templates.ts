import { createShapeId, toRichText, type TLParentId } from '@tldraw/tlschema';
import { getIndicesBetween, type IndexKey } from '@tldraw/utils';
import type { TLShape } from 'tldraw';

/**
 * Curated starter canvases. Each template is a small hand-built tldraw
 * document (document-scope records only, the same format the room save path
 * persists) so a room can be created pre-populated. Seeding happens
 * client-side: buildTemplateSeed returns the canonical record map JSON, and
 * `createRoom({ seed })` stores it as the room's initial canvasData.
 *
 * The records are validated against tldraw's own schema in
 * `src/lib/templates.test.ts` so a malformed template fails the test suite
 * before it can ever reach a real room.
 */

export interface TemplateDef {
  id: string;
  name: string;
  tagline: string;
  category: 'architecture' | 'wireframe' | 'planning';
  /** Accent used by the template card, one of the app's neutral/green tokens. */
  accent: 'green' | 'ink';
}

